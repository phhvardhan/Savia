"""
Agent output (each agent's own JSON shape) -> BrandDocument. Agents and their
prompts are unchanged; this is the only place their shapes meet the brand.
"""
from typing import Any

from app.brand.document import BrandDocument, Field, Item, Section
from app.core.export import _cell_text, _is_records, _label, _unique_sections

SKIP_KEYS = {"title"}
# Keys that name a record, in preference order; used for the record's title line.
TITLE_KEYS = ("title", "name", "summary", "task", "requirement", "decision", "risk", "question",
              "component", "option", "phase", "gap", "change", "test_case", "scenario")


def _is_id(key: str) -> bool:
    k = key.lower()
    return k == "id" or k.endswith("_id") or k.endswith(" id")


def _fields(record: dict, skip: set) -> list[Field]:
    return [Field(label=_label(k), value=_cell_text(v)) for k, v in record.items()
            if k not in skip and _cell_text(v).strip()]


def _item(record: dict) -> Item:
    id_key = next((k for k in record if _is_id(k) and _cell_text(record[k]).strip()), None)
    title_key = next((k for k in TITLE_KEYS if _cell_text(record.get(k)).strip()), None)
    title = " · ".join(_cell_text(record[k]) for k in (id_key, title_key) if k) or None
    return Item(title=title, fields=_fields(record, {id_key, title_key}))


def _section(key: str, value: Any) -> Section | None:
    if _is_records(value):
        section = Section(heading=_label(key), items=[_item(r) for r in value])
    elif isinstance(value, dict):
        section = Section(heading=_label(key), items=[Item(fields=_fields(value, set()))])
    elif isinstance(value, list):
        section = Section(heading=_label(key), body=[t for t in (_cell_text(v) for v in value) if t.strip()])
    else:
        text = _cell_text(value)
        section = Section(heading=_label(key), body=[text] if text.strip() else [])
    return section if section.body or any(i.fields or i.title for i in section.items) else None


def to_brand_document(title: str, subtitle: str, content: dict) -> BrandDocument:
    sections = [s for key, value in _unique_sections(content) if key not in SKIP_KEYS
                for s in [_section(key, value)] if s]
    # Cover band: headline + "Generated by SAVIA ..." subhead. Footer repeats it on every page.
    return BrandDocument(headline=title, subhead=subtitle, sections=sections, footer=subtitle)
