# --- Routes: Word export and the preview share renderer + validator ---------

def test_export_and_preview_routes(monkeypatch, no_brand_fonts):
    from fastapi.testclient import TestClient
    from app.main import app
    from app.models.workflow import Artifact, StageEnum
    from app.orchestration.workflow_engine import workflow_engine

    art = Artifact(workflow_id="wf-test", agent_name="mom", stage=list(StageEnum)[0], version=1, content=MOM)
    monkeypatch.setitem(workflow_engine._memory_artifacts, art.artifact_id, art)  # in memory only, nothing on disk
    (no_brand_fonts / "JohnsonText-Regular.otf").write_bytes(b"font")
    client = TestClient(app)

    r = client.get(f"/api/v1/workflows/artifacts/{art.artifact_id}/export.docx")
    assert r.status_code == 200
    assert _headline(Document(io.BytesIO(r.content))).text == MOM["title"]

    body = client.get(f"/api/v1/workflows/artifacts/{art.artifact_id}/brand-document").json()
    assert body["document"]["headline"] == MOM["title"]
    assert body["styles"]["body"]["font_family"] == "Johnson Text"
    assert body["styles"]["headline"]["font_family"] == "Arial"
    assert body["page_background"] == "FFFFFF"
    assert body["styles"]["headline"]["background"] == "EB1700"
    assert body["fonts"] == [{"family": "Johnson Text", "weight": 400, "file": "JohnsonText-Regular.otf"}]

    assert client.get("/api/v1/workflows/brand/fonts/JohnsonText-Regular.otf").content == b"font"
    assert client.get("/api/v1/workflows/brand/fonts/..%2F..%2F.env").status_code == 404


# --- PowerPoint deck ---------------------------------------------------------

BLUEPRINT = {
    "title": "Solution Blueprint: Stock sync",
    "executive_summary": "Move from a nightly file to events.",
    "proposed_solution": {"approach": "Event-driven sync.", "rationale": "Removes the delay."},
    "risks": [{"risk": "Volume", "impact": "High", "mitigation": "Queue"}],
    "needs_info": ["Daily volumes?"],
}


def _deck():
    from pptx import Presentation
    from app.core.deck import solution_to_pptx
    return Presentation(io.BytesIO(solution_to_pptx(BLUEPRINT, "Prepared with SAVIA")))


def _runs(prs):
    for slide in prs.slides:
        for shape in slide.shapes:
            if shape.has_text_frame:
                for p in shape.text_frame.paragraphs:
                    yield from (r for r in p.runs if r.text.strip())


def _pptx_problems(prs) -> str:
    from app.brand.validator import validate_pptx
    with pytest.raises(BrandViolation) as e:
        validate_pptx(prs)
    return str(e.value)


def test_deck_is_branded(no_brand_fonts):
    (no_brand_fonts / "JohnsonText-Regular.otf").write_bytes(b"")
    (no_brand_fonts / "JohnsonDisplay-Bold.otf").write_bytes(b"")
    prs = _deck()  # solution_to_pptx already ran validate_pptx
    title_bg = prs.slides[0].shapes[0]
    assert str(title_bg.fill.fore_color.rgb) == "EB1700"
    names = {r.font.name for r in _runs(prs)}
    assert names == {"Johnson Text", "Johnson Display"}
    assert not any(is_caps(r.text) for r in _runs(prs))


def is_caps(text):
    from app.brand.document import is_all_caps
    return is_all_caps(text)


def test_pptx_validator_rejects_all_caps_and_small_display(no_brand_fonts):
    (no_brand_fonts / "JohnsonDisplay-Bold.otf").write_bytes(b"")
    (no_brand_fonts / "JohnsonText-Regular.otf").write_bytes(b"")
    prs = _deck()
    runs = [r for r in _runs(prs) if r.font.name == "Johnson Text" and not r.font.bold]
    runs[0].text = "SHOUTING TEXT"
    runs[1].font.name = "Johnson Display"
    problems = _pptx_problems(prs)
    assert "all caps" in problems
    assert "Johnson Display at" in problems


def test_pptx_validator_rejects_wrong_colour_pairings():
    from pptx.dml.color import RGBColor
    prs = _deck()
    on_white = next(r for r in _runs(prs) if not r.font.bold and str(r.font.color.rgb) == "000000")
    on_white.font.color.rgb = RGBColor.from_string("EB1700")
    on_red = next(r for r in _runs(prs) if str(r.font.color.rgb) == "FFFFFF")  # title slide
    on_red.font.color.rgb = RGBColor.from_string("000000")
    problems = _pptx_problems(prs)
    assert "red copy on white" in problems
    assert "only white text on J&J Red" in problems
