def _doc(**overrides):
    return render(BrandDocument(**{"headline": "Weekly sync", "sections": [Section(heading="Summary", body=["All good."])],
                                   "footer": "Generated by SAVIA", **overrides}))


def _cover(doc):
    return doc.tables[0].cell(0, 0)


def _headline(doc):
    return next(p for p in _cover(doc).paragraphs if p.style.name == "Brand Headline")


def _body_run(doc):
    return next(p for p in doc.paragraphs if p.style.name == "Brand Body").runs[0]


def _problems(doc) -> str:
    with pytest.raises(BrandViolation) as e:
        validate_docx(doc)
    return str(e.value)


# --- Smoke: a real agent output renders and passes -------------------------

def test_agent_output_renders_branded_docx():
    doc = Document(io.BytesIO(render_artifact_docx(MOM["title"], "Generated by SAVIA · MOM · version 1", MOM)))
    styles = [p.style.name for p in doc.paragraphs]
    assert [p.text for p in _cover(doc).paragraphs] == ["Weekly sync: stock visibility", "Generated by SAVIA · MOM · version 1"]
    assert _cover(doc)._tc.xpath("./w:tcPr/w:shd/@w:fill") == ["EB1700"]  # red cover band
    assert "Brand Section heading" in styles and "Brand Body" in styles
    assert "Title" not in [p.text for p in doc.paragraphs]  # title is the headline, not a section
    assert [p.text for p in doc.paragraphs if p.style.name == "Brand Section heading"] == [
        "Summary", "Key points", "Action items", "Open questions"]
    assert doc.sections[0].footer.paragraphs[0].text == "Generated by SAVIA · MOM · version 1"
    assert doc.styles["Brand Body"].font.name == "Arial"  # no font files -> fallback
    validate_docx(doc)


# --- Normalisation ---------------------------------------------------------

def test_all_caps_input_is_sentence_cased():
    d = BrandDocument(headline="DELIVERY READINESS SCORECARD", footer="",
                      sections=[Section(heading="OPEN QUESTIONS", body=["THE SYSTEM WILL FAIL.\nSAP is fine"])])
    assert d.headline == "Delivery readiness scorecard"
    assert d.sections[0].heading == "Open questions"
    assert d.sections[0].body == ["The system will fail.\nSAP is fine"]
    assert sentence_case("KDD for DAB") == "KDD for DAB"  # mixed case keeps its acronyms
    assert sentence_case("SAP S/4HANA") == "SAP S/4HANA"  # acronyms alone are not shouting
    assert sentence_case("THE SAP SYSTEM WILL FAIL") == "The SAP system will fail"


# --- Validator --------------------------------------------------------------

def test_validator_rejects_all_caps():
    doc = _doc()
    _body_run(doc).text = "THIS IS SHOUTING"
    assert "all caps" in _problems(doc)


def test_validator_rejects_caps_formatting():
    doc = _doc()
    _body_run(doc).font.all_caps = True
    assert "all_caps" in _problems(doc)


def test_validator_rejects_display_font_for_body():
    doc = _doc()
    _body_run(doc).font.name = "Johnson Display"
    assert "Johnson Display is for headlines and subheads, never body copy" in _problems(doc)


def test_validator_rejects_wrong_font_with_johnson_fonts_present(no_brand_fonts):
    (no_brand_fonts / "JohnsonText-Regular.otf").write_bytes(b"")
    (no_brand_fonts / "JohnsonDisplay-Bold.otf").write_bytes(b"")
    doc = _doc()
    validate_docx(doc)
    _headline(doc).runs[0].font.name = "Johnson Text"  # headline must be Display
    assert "expected 'Johnson Display'" in _problems(doc)


def test_validator_rejects_red_body_text_on_white():
    doc = _doc()
    validate_docx(doc)
    _body_run(doc).font.color.rgb = RGBColor.from_string("EB1700")
    assert "red text on white" in _problems(doc)


def test_validator_rejects_black_text_on_red():
    doc = _doc()
    body = next(p for p in doc.paragraphs if p.style.name == "Brand Body")
    body._p.get_or_add_pPr().append(parse_xml(f'<w:shd {nsdecls("w")} w:val="clear" w:fill="EB1700"/>'))
    assert "black text on red" in _problems(doc)


def test_validator_rejects_effects_and_centering():
    doc = _doc()
    _body_run(doc).font.shadow = True
    _headline(doc).alignment = WD_ALIGN_PARAGRAPH.CENTER
    problems = _problems(doc)
    assert "'shadow' is not allowed" in problems
    assert "must be left aligned" in problems


